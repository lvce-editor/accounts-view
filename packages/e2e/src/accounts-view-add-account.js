export const test = async ({ document, assert, waitFor }) => {
  const accounts = () => document.querySelector('ul[aria-label="Connected accounts"]')
  const add = document.querySelector('button[name="add-account"]')
  assert(add.textContent === 'Add Another Account', 'Missing additional login action')
  add.click()
  await waitFor(() => accounts().children.length === 1, 'Login did not add exactly one account')
  document.querySelector('button[name="add-account"]').click()
  await waitFor(() => accounts().children.length === 2, 'Repeated login did not add exactly one account')
  assert(document.querySelectorAll('button[disabled]').length === 1, 'Expected exactly one active account')
  document.querySelector('button[name="use-account:account-1"]').click()
  await waitFor(() => document.querySelector('button[name="use-account:account-1"]').disabled, 'First account was not activated')
  assert(!document.querySelector('button[name="use-account:account-2"]').disabled, 'Previous account remained active')
  document.querySelector('button[name="use-account:account-2"]').click()
  await waitFor(() => document.querySelector('button[name="use-account:account-2"]').disabled, 'Second account was not activated')
  document.querySelector('button[name="sign-out:account-1"]').click()
  await waitFor(() => accounts().children.length === 1, 'Sign out did not remove one account')
  assert(document.querySelector('[role="status"]')?.textContent === '1 account connected', 'Incorrect count after sign out')
  assert(document.querySelector('button[name="use-account:account-2"]').disabled, 'Remaining account lost active state')
}
